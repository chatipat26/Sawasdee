from sqlalchemy import Column, String, Numeric, Integer, Boolean, Text, DateTime, Date, JSON, func
from sqlalchemy.orm import declarative_base

Base = declarative_base()


class Vehicle(Base):
    __tablename__ = "cars"

    plate = Column(String(50), primary_key=True, index=True)
    brand = Column(String(100), nullable=True)
    model = Column(String(100), nullable=True)
    car_group = Column(String(100), default="รถเก๋ง (Sedan/Hatchback)")
    fuel_system = Column(String(50), default="เบนซิน")
    cc_ev = Column(String(50), default="1200")
    owner_company = Column(String(150), default="Sawasdee Rent A Car")
    color = Column(String(50), default="-")
    mileage = Column(String(50), default="0")
    daily_rate = Column(Numeric, default=0.0)
    weekly_rate = Column(Numeric, default=0.0)
    monthly_rate = Column(Numeric, default=0.0)
    vin = Column(String(100), default="-")
    tax_expire_date = Column(String(50), default="-")
    prb_expire_date = Column(String(50), default="-")
    insurance_expire_date = Column(String(50), default="-")
    insurance_company = Column(String(150), default="-")
    car_owner = Column(String(150), default="-")
    beneficiary = Column(String(150), default="-")
    register_year = Column(String(50), default="-")
    prb_price = Column(Numeric, default=0.0)
    insurance_premium = Column(Numeric, default=0.0)
    owner_name = Column(String(150), default="-")
    registration_year = Column(String(50), default="-")
    last_service_date = Column(String(50), default="-")
    next_service_date = Column(String(50), default="-")
    next_service_mileage = Column(Numeric, default=0.0)
    car_status = Column(String(50), default="ว่างพร้อมใช้งาน")
    is_debt_free = Column(Boolean, default=False)
    finance_company = Column(String(150), default="-")
    installment_amount = Column(Numeric, default=0.0)
    total_installments = Column(Integer, default=0)
    current_installment = Column(Integer, default=0)
    payment_due_date = Column(String(50), default="-")
    notes = Column(Text, default="")
    image_url = Column(Text, default="")
    created_at = Column(DateTime(timezone=True), server_default=func.now())


Car = Vehicle


class Customer(Base):
    __tablename__ = "customers"

    full_name = Column(String(150), primary_key=True, index=True)
    phone_number = Column(String(50), nullable=True)
    id_card_no = Column(String(50), nullable=True)
    driver_license_no = Column(String(50), nullable=True)
    nationality = Column(String(50), default="THAI")
    whatsapp = Column(String(50), default="-")
    dob = Column(String(50), default="-")
    license_expire_date = Column(String(50), default="-")
    home_address = Column(Text, default="-")
    current_address = Column(Text, default="-")

    # Backward compatibility columns
    contact_no = Column(String(50), nullable=True)
    phone = Column(String(50), nullable=True)
    passport_id = Column(String(50), nullable=True)
    id_card = Column(String(50), nullable=True)
    licence_no = Column(String(50), nullable=True)
    driver_license = Column(String(50), nullable=True)
    licence_expiry = Column(String(50), default="-")
    thai_address = Column(Text, default="-")
    address = Column(Text, default="-")
    nickname = Column(String(100), nullable=True)
    email = Column(String(150), nullable=True)
    line_id = Column(String(100), nullable=True)
    line_user_id = Column(Text, nullable=True)
    notes = Column(Text, default="")
    id_card_photo = Column(Text, nullable=True)
    driver_license_photo = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

class VehicleMaintenance(Base):
    __tablename__ = "vehicle_maintenances"

    id = Column(Integer, primary_key=True, autoincrement=True, index=True)
    car_id = Column(String(50), nullable=False, index=True)
    date = Column(String(50), nullable=False)
    description = Column(Text, nullable=False)
    cost = Column(Numeric, default=0.0)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

class WorkOrderLog(Base):
    __tablename__ = "work_order_logs"

    id = Column(String(100), primary_key=True, index=True)
    car_id = Column(String(100), nullable=True, index=True)
    booking_id = Column(String(100), nullable=True, index=True)
    work_type = Column(String(100), nullable=True) # 'Dispatch', 'Return', 'Renew Tax', etc.
    description = Column(Text, nullable=True)
    cost = Column(Numeric, default=0.0)
    staff_id = Column(String(150), nullable=True)
    appointment_datetime = Column(DateTime(timezone=True), nullable=True)
    location = Column(Text, nullable=True)
    job_status = Column(String(50), default="Pending")
    created_at = Column(DateTime(timezone=True), server_default=func.now())


class Booking(Base):
    __tablename__ = "bookings"

    booking_id = Column(String(50), primary_key=True, index=True)
    car_id = Column(String(50), nullable=True, index=True)
    customer = Column(String(200), nullable=True)
    start_date = Column(Date, nullable=True)
    start_time = Column(String(20), default="09:00")
    end_date = Column(Date, nullable=True)
    end_time = Column(String(20), default="09:00")
    total_days = Column(Numeric, default=1)
    daily_rate = Column(Numeric, default=0.0)
    total_price = Column(Numeric, default=0.0)
    base_price = Column(Numeric, default=0.0)
    discount = Column(Numeric, default=0.0)
    net_price = Column(Numeric, default=0.0)
    deposit_paid = Column(Boolean, default=False)
    deposit_amount = Column(Numeric, default=5000.0)
    deposit_payment_method = Column(String(100), default="เงินสด")
    rental_paid = Column(Boolean, default=False)
    rental_amount_paid = Column(Numeric, default=0.0)
    remaining_rental = Column(Numeric, default=0.0)
    rental_payment_method = Column(String(100), default="เงินสด")
    status = Column(String(50), default="รอชำระมัดจำ")
    loc_delivery = Column(Text, default="Sukhumvit")
    loc_return = Column(Text, default="Sukhumvit")
    worker_delivery = Column(String(100), nullable=True)
    worker_return = Column(String(100), nullable=True)
    dispatch_closed = Column(Boolean, default=False)
    return_closed = Column(Boolean, default=False)
    dispatch_date = Column(DateTime(timezone=True), nullable=True)
    return_date = Column(DateTime(timezone=True), nullable=True)
    dispatch_mileage = Column(String(50), nullable=True)
    return_mileage = Column(String(50), nullable=True)
    dispatch_fuel = Column(String(50), nullable=True)
    return_fuel = Column(String(50), nullable=True)
    dispatch_notes = Column(Text, nullable=True)
    return_notes = Column(Text, nullable=True)
    dispatch_photos = Column(JSON, default=list)
    return_photos = Column(JSON, default=list)
    payment_slip_url = Column(Text, nullable=True)
    payment_type = Column(String(50), nullable=True)
    google_drive_link = Column(Text, nullable=True)
    contract_issued = Column(Boolean, default=False)
    contract_type = Column(String(50), default="รายวัน")
    extension_history = Column(JSON, default=list)
    is_fully_paid = Column(Boolean, default=False)
    contract_pdf_url = Column(Text, nullable=True)
    checkout_pdf_url = Column(String(500), nullable=True)
    checkin_pdf_url = Column(String(500), nullable=True)
    inspection_categories = Column(JSON, nullable=True)
    inspection_categories_out = Column(JSON, nullable=True)
    inspection_categories_in = Column(JSON, nullable=True)
    created_by = Column(String(100), default="admin")
    created_at = Column(DateTime(timezone=True), server_default=func.now())




class MaintenanceRecord(Base):
    __tablename__ = "maintenance_records"

    id = Column(String(50), primary_key=True, index=True)
    car_id = Column(String(50), nullable=False, index=True)
    car_brand = Column(String(100), nullable=True)
    car_model = Column(String(100), nullable=True)
    car_color = Column(String(50), nullable=True)
    order_type = Column(String(100), nullable=True)
    service_items = Column(Text, nullable=True)
    cost = Column(Numeric, default=0.0)
    actual_cost = Column(Numeric, default=0.0)
    service_center = Column(String(150), nullable=True)
    service_center_phone = Column(String(50), nullable=True)
    service_location = Column(String(150), nullable=True)
    assigned_worker = Column(String(100), nullable=True)
    schedule_date = Column(Date, nullable=True)
    schedule_time = Column(String(50), nullable=True)
    expected_finish_date = Column(Date, nullable=True)
    expected_finish_time = Column(String(50), nullable=True)
    status = Column(String(50), default="รอดำเนินการ", index=True)
    current_mileage = Column(String(50), nullable=True)
    notes = Column(Text, nullable=True)
    completion_notes = Column(Text, nullable=True)
    update_car_status = Column(Boolean, default=True)
    created_by = Column(String(100), nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    completed_at = Column(DateTime(timezone=True), nullable=True)
    new_act_expiry = Column(String(50), nullable=True)
    new_ins_expiry = Column(String(50), nullable=True)
    new_tax_expiry = Column(String(50), nullable=True)
    insurance_company = Column(String(150), nullable=True)
